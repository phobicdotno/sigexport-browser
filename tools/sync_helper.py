#!/usr/bin/env python3
"""Localhost helper that lets the offline viewer (file://) and the Dock app start a re-sync.

Endpoints (127.0.0.1 only):
  POST /sync    start pipeline/sync.py detached -> 202 {"started": true}
                already running                 -> 409 {"busy": true}
  GET  /status  contents of OUT/_state/sync_status.json ({"state": "idle"} if none yet)
  GET  /log?lines=N   tail (max 500 lines) of OUT/_state/sync.log for the current/last run
                      (from the last "step=disk" line on) -> {"lines": [...], "failed_chats": n}
  POST /zip-ticket?chat=N   -> {"ticket": "...", "files": n}: short-lived (60 s), single-use ticket
  GET  /media.zip?chat=N&ticket=T   streams a zip of chat N's photos/videos (the ticket replaces the
                      token header so the browser can download it natively). Only files referenced in
                      OUT/viewer/data/N.js, resolved inside OUT/Media or that chat's own folder.
  POST /file-ticket?chat=N&ref=R  -> {"ticket": "...", "name": "..."}: same 60 s single-use ticket for one
                      attachment; R must be an attachment path listed in OUT/viewer/data/N.js
  GET  /file?ticket=T streams that one file as an attachment (Content-Disposition filename*=UTF-8''name)
                      so the file:// viewer can save it straight to disk
  OPTIONS *     CORS preflight

Security:
  - binds 127.0.0.1 only; the Host header must be 127.0.0.1:PORT or localhost:PORT
  - every GET/POST needs header X-Sync-Token = the token in OUT/viewer/sync_config.js
    (generated by tools/install_sync.py, local only, never committed or uploaded)
  - Origin must be absent (curl), "null" (the file:// viewer) or the helper's own origin

The helper never syncs by itself: it only launches the sync engine with the fixed CLI
  PYTHON SYNC_PY --out OUT [--upload]
and reports its status file. Exit code 75 from sync.py means "already running".

With ARCHIVE_URL set (archive on another machine) the helper also polls ARCHIVE_URL/sync-request
every ARCHIVE_POLL_SECS (45) s and starts a sync when the hosted viewer queued one.

Also usable as a CLI for the Dock app:  sync_helper.py --print-status --out OUT [--since EPOCH]
prints "state<TAB>added_messages<TAB>new_media<TAB>step<TAB>message" (state "stale" if the status
file is older than EPOCH).
"""
import argparse
import hmac
import json
import mimetypes
import shutil
import os
import re
import secrets
import zipfile
from urllib.parse import parse_qs, quote, unquote, urlsplit
import subprocess
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

try:
    import fcntl
except ImportError:  # Windows: lock probing falls back to the exit-75 check
    fcntl = None

DEFAULT_PORT = 8765
EX_BUSY = 75
TOKEN_RE = re.compile(r"token\s*:\s*['\"]([A-Za-z0-9_\-]+)['\"]")


def read_token(out):
    try:
        m = TOKEN_RE.search((Path(out) / "viewer" / "sync_config.js").read_text(encoding="utf-8"))
        return m.group(1) if m else None
    except OSError:
        return None


def read_status(out):
    p = Path(out) / "_state" / "sync_status.json"
    try:
        return json.loads(p.read_text(encoding="utf-8")), p.stat().st_mtime
    except (OSError, ValueError):
        return {"state": "idle"}, 0.0


LOG_MAX = 500
FAILED_RE = re.compile(r"\bchat NNN=\d+ failed\b")


def read_log(out, lines=200):
    """Tail of sync.log for the current or last run: from the last 'step=disk' line on."""
    try:
        text = (Path(out) / "_state" / "sync.log").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return [], 0
    all_lines = text.splitlines()
    start = 0
    for i in range(len(all_lines) - 1, -1, -1):
        if "step=disk" in all_lines[i]:
            start = i
            break
    run = all_lines[start:]
    failed = sum(1 for ln in run if FAILED_RE.search(ln))
    n = max(1, min(LOG_MAX, int(lines)))
    return run[-n:], failed


SAFE_NAME_RE = re.compile(r'[\\/:*?"<>|\x00-\x1f]+')


def load_chat(out, chat_id):
    """(chat dict, viewer dir, allowed roots) or None. Roots: OUT/Media and the chat's own folder."""
    if not re.fullmatch(r"\d{1,6}", str(chat_id)):
        return None
    root = Path(out).resolve()
    viewer = root / "viewer"
    try:
        js = (viewer / "data" / ("%d.js" % int(chat_id))).read_text(encoding="utf-8")
        chat = json.loads(js[js.index("]=") + 2:].rstrip().rstrip(";"))
    except (OSError, ValueError):
        return None
    roots = [(root / "Media").resolve()]
    d = chat.get("dir") or ""
    if d:
        cd = (root / d.split("/")[0]).resolve()
        if cd != root and cd.is_relative_to(root):
            roots.append(cd)
    return chat, viewer, roots


def resolve_ref(viewer, roots, p):
    """Absolute file for attachment path p, or None if outside the roots / missing / a URL."""
    if not p or ":" in p.split("/")[0]:
        return None
    f = (viewer / unquote(p.split("#")[0].split("?")[0])).resolve()
    if not any(f.is_relative_to(r) for r in roots) or not f.is_file():
        return None
    return f


def safe_name(a, f):
    return SAFE_NAME_RE.sub("_", a.get("name") or f.name).lstrip(".") or f.name


def chat_file(out, chat_id, ref):
    """(abs_path, download name) for attachment ref listed in chat chat_id, else None."""
    got = load_chat(out, chat_id)
    if got is None or not ref:
        return None
    chat, viewer, roots = got
    for m in chat.get("messages", []):
        for a in m.get("a", []):
            if a.get("path") == ref and a.get("ok"):
                f = resolve_ref(viewer, roots, ref)
                return (f, safe_name(a, f)) if f else None
    return None


def chat_media(out, chat_id):
    """[(abs_path, arcname)] of chat chat_id's ok photos/videos, only inside OUT/Media or the chat's folder."""
    got = load_chat(out, chat_id)
    if got is None:
        return None
    chat, viewer, roots = got
    files, seen, names = [], set(), set()
    for m in chat.get("messages", []):
        for a in m.get("a", []):
            if a.get("type") not in ("image", "video") or not a.get("ok"):
                continue
            f = resolve_ref(viewer, roots, a.get("path") or "")
            if f is None or f in seen:
                continue
            seen.add(f)
            nm = safe_name(a, f)
            base, ext = os.path.splitext(nm)
            k, cand = 1, nm
            while cand.lower() in names:
                k += 1
                cand = "%s (%d)%s" % (base, k, ext)
            names.add(cand.lower())
            files.append((f, cand))
    return files, chat.get("name") or ("chat %s" % chat_id)


class Tickets:
    def __init__(self, ttl=60):
        self.ttl, self.t, self.lock = ttl, {}, threading.Lock()

    def issue(self, chat_id):
        return self.issue_payload(str(chat_id))

    def issue_payload(self, payload):
        tk = secrets.token_urlsafe(24)
        with self.lock:
            now = time.time()
            self.t = {k: v for k, v in self.t.items() if v[1] > now}
            self.t[tk] = (payload, now + self.ttl)
        return tk

    def take(self, tk, chat_id):
        v = self.pop(tk)
        return v is not None and v == str(chat_id)

    def pop(self, tk):
        """Payload of a valid ticket (consumed), else None."""
        with self.lock:
            v = self.t.pop(tk or "", None)
        return v[0] if v is not None and v[1] > time.time() else None


def lock_held(out):
    """True if another process holds an flock on OUT/_state/sync.lock."""
    if fcntl is None:
        return False
    p = Path(out) / "_state" / "sync.lock"
    if not p.exists():
        return False
    try:
        with open(p, "a") as f:
            try:
                fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError:
                return True
            fcntl.flock(f, fcntl.LOCK_UN)
    except OSError:
        return False
    return False


class Runner:
    """Starts sync.py detached and remembers the child so a second click reports busy."""

    def __init__(self, out, python, sync_py, upload, extra_args=()):
        self.out, self.python, self.sync_py, self.upload = str(out), python, str(sync_py), upload
        self.extra_args = list(extra_args)
        self.proc = None
        self.lock = threading.Lock()

    def start(self):
        with self.lock:
            if self.proc is not None and self.proc.poll() is None:
                return 409, {"busy": True}
            if lock_held(self.out):
                return 409, {"busy": True}
            if not Path(self.sync_py).is_file():
                return 500, {"error": "sync.py not found: " + self.sync_py}
            cmd = [self.python, self.sync_py, "--out", self.out] + (["--upload"] if self.upload else []) + self.extra_args
            state = Path(self.out) / "_state"
            state.mkdir(parents=True, exist_ok=True)
            log = open(state / "sync_launch.log", "ab")
            log.write(("\n== %s %s\n" % (time.strftime("%Y-%m-%d %H:%M:%S"), " ".join(cmd))).encode())
            log.flush()
            kw = {"start_new_session": True} if os.name == "posix" else {}
            self.proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=log, stderr=log, close_fds=True, **kw)
            log.close()
            proc = self.proc
            threading.Thread(target=proc.wait, daemon=True).start()  # reap, no zombies
            # sync.py exits 75 at once if another run (Dock app, 03:00 job) holds the lock
            deadline = time.time() + 1.5
            while time.time() < deadline:
                rc = proc.poll()
                if rc is not None:
                    if rc == EX_BUSY:
                        return 409, {"busy": True}
                    if rc != 0:
                        return 500, {"error": "sync.py exited with %d (see _state/sync.log)" % rc}
                    break
                time.sleep(0.1)
            return 202, {"started": True}


def disposition(fn):
    ascii_fn = re.sub(r"[^A-Za-z0-9._ -]", "_", fn)
    return "attachment; filename=\"%s\"; filename*=UTF-8''%s" % (ascii_fn, quote(fn, safe=""))


def make_handler(out, port, runner, tickets=None):
    tickets = tickets or Tickets()
    own = {"http://127.0.0.1:%d" % port, "http://localhost:%d" % port}
    hosts = {"127.0.0.1:%d" % port, "localhost:%d" % port}

    class H(BaseHTTPRequestHandler):
        server_version = "sigexport-sync-helper"

        def log_message(self, fmt, *args):
            sys.stderr.write("%s %s\n" % (time.strftime("%Y-%m-%d %H:%M:%S"), fmt % args))

        def _origin_ok(self):
            o = self.headers.get("Origin")
            return o is None or o == "null" or o in own

        def _send(self, code, obj):
            body = json.dumps(obj).encode()
            self.send_response(code)
            o = self.headers.get("Origin")
            if o is not None and self._origin_ok():
                self.send_header("Access-Control-Allow-Origin", o)
                self.send_header("Vary", "Origin")
            self.send_header("Content-Type", "application/json")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def _guard(self, token=True):
            if self.headers.get("Host") not in hosts:
                self._send(403, {"error": "bad host"})
                return False
            if not self._origin_ok():
                self._send(403, {"error": "origin not allowed"})
                return False
            if not token:
                return True
            tok, got = read_token(out), self.headers.get("X-Sync-Token") or ""
            if not tok or not hmac.compare_digest(tok.encode(), got.encode()):
                self._send(401, {"error": "bad or missing token"})
                return False
            return True

        def do_OPTIONS(self):
            if self.headers.get("Host") not in hosts or not self._origin_ok():
                self._send(403, {"error": "origin not allowed"})
                return
            self.send_response(204)
            o = self.headers.get("Origin")
            if o is not None:
                self.send_header("Access-Control-Allow-Origin", o)
                self.send_header("Vary", "Origin")
            self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
            self.send_header("Access-Control-Allow-Headers", "X-Sync-Token")
            self.send_header("Access-Control-Allow-Private-Network", "true")
            self.send_header("Access-Control-Max-Age", "600")
            self.send_header("Content-Length", "0")
            self.end_headers()

        def _zip(self, q):
            cid, tk = (q.get("chat") or [""])[0], (q.get("ticket") or [""])[0]
            if not tickets.take(tk, cid):
                self._send(401, {"error": "bad or expired ticket"})
                return
            got = chat_media(out, cid)
            if got is None:
                self._send(404, {"error": "no such chat"})
                return
            files, name = got
            fn = (re.sub(r'[\\/:*?"<>|\x00-\x1f]+', "_", name).strip() or "chat") + " - media.zip"
            self.send_response(200)
            self.send_header("Content-Type", "application/zip")
            self.send_header("Content-Disposition", disposition(fn))
            self.send_header("Cache-Control", "no-store")
            self.send_header("Connection", "close")
            self.end_headers()
            self.close_connection = True
            try:
                with zipfile.ZipFile(self.wfile, "w", zipfile.ZIP_STORED, allowZip64=True) as z:
                    for f, arc in files:
                        z.write(f, arc)
            except (OSError, ValueError):
                pass  # client went away

        def _file(self, q):
            v = tickets.pop((q.get("ticket") or [""])[0])
            if not isinstance(v, tuple):
                self._send(401, {"error": "bad or expired ticket"})
                return
            got = chat_file(out, v[0], v[1])
            if got is None:
                self._send(404, {"error": "not found"})
                return
            f, fn = got
            try:
                fh = open(f, "rb")
                size = os.fstat(fh.fileno()).st_size
            except OSError:
                self._send(404, {"error": "not found"})
                return
            with fh:
                self.send_response(200)
                self.send_header("Content-Type", mimetypes.guess_type(f.name)[0] or mimetypes.guess_type(fn)[0]
                                 or "application/octet-stream")
                self.send_header("Content-Length", str(size))
                self.send_header("Content-Disposition", disposition(fn))
                self.send_header("X-Content-Type-Options", "nosniff")
                self.send_header("Cache-Control", "no-store")
                self.end_headers()
                try:
                    shutil.copyfileobj(fh, self.wfile, 1 << 20)
                except OSError:
                    pass  # client went away

        def do_GET(self):
            u = urlsplit(self.path)
            q = parse_qs(u.query)
            if u.path == "/media.zip":
                if self._guard(token=False):
                    self._zip(q)
                return
            if u.path == "/file":
                if self._guard(token=False):
                    self._file(q)
                return
            if not self._guard():
                return
            if u.path == "/status":
                st = read_status(out)[0]
                if st.get("state") == "failed" and "failed_chats" not in st:
                    st["failed_chats"] = read_log(out, 1)[1]
                self._send(200, st)
            elif u.path == "/log":
                try:
                    n = int((q.get("lines") or ["200"])[0])
                except ValueError:
                    n = 200
                lines, failed = read_log(out, n)
                self._send(200, {"lines": lines, "failed_chats": failed, "state": read_status(out)[0].get("state", "idle")})
            else:
                self._send(404, {"error": "not found"})

        def do_POST(self):
            if not self._guard():
                return
            u = urlsplit(self.path)
            if u.path == "/sync":
                code, obj = runner.start()
                self._send(code, obj)
            elif u.path == "/zip-ticket":
                cid = (parse_qs(u.query).get("chat") or [""])[0]
                got = chat_media(out, cid)
                if got is None:
                    self._send(404, {"error": "no such chat"})
                elif not got[0]:
                    self._send(404, {"error": "no media"})
                else:
                    self._send(200, {"ticket": tickets.issue(cid), "files": len(got[0])})
            elif u.path == "/file-ticket":
                q = parse_qs(u.query)
                cid, ref = (q.get("chat") or [""])[0], (q.get("ref") or [""])[0]
                got = chat_file(out, cid, ref)
                if got is None:
                    self._send(404, {"error": "not found"})
                else:
                    self._send(200, {"ticket": tickets.issue_payload((str(cid), ref)), "name": got[1]})
            else:
                self._send(404, {"error": "not found"})

    return H


def poll_archive_once(client, runner):
    """Archive on another machine: claim a pending sync request from the hosted viewer
    (ARCHIVE_URL/sync-request) and start a sync. Returns True when one was started."""
    try:
        if not client.claim_sync_request():
            return False
    except Exception:  # noqa: BLE001  host down: try again next poll
        return False
    code, _obj = runner.start()
    return code == 202


def start_archive_poller(runner, url, token_file, every=45):
    """Background thread: every `every` s claim ARCHIVE_URL/sync-request (sync.py itself reports
    progress back with POST ARCHIVE_URL/status)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "pipeline"))
    import archive_client as AC

    def loop():
        while True:
            try:
                client = AC.ArchiveClient(url, AC.read_token_file(token_file or None), timeout=15)
                poll_archive_once(client, runner)
            except Exception:  # noqa: BLE001
                pass
            time.sleep(every)
    t = threading.Thread(target=loop, daemon=True)
    t.start()
    return t


def serve(out, port, runner):
    httpd = ThreadingHTTPServer(("127.0.0.1", port), make_handler(out, port, runner))
    httpd.daemon_threads = True
    return httpd


def print_status(out, since):
    st, mtime = read_status(out)
    state = st.get("state", "idle")
    if since and mtime < since:
        state = "stale"
    clean = lambda v: str(v if v is not None else "").replace("\t", " ").replace("\n", " ")
    print("\t".join(clean(x) for x in (state, st.get("added_messages", 0), st.get("new_media", 0),
                                         st.get("step", ""), st.get("message", ""))))


def main(argv=None):
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.environ.get("OUT_DIR", str(Path.home() / "SignalExport")))
    ap.add_argument("--port", type=int, default=int(os.environ.get("SYNC_PORT", DEFAULT_PORT)))
    ap.add_argument("--python", default=sys.executable, help="interpreter for sync.py")
    ap.add_argument("--sync", default=str(here.parent / "pipeline" / "sync.py"), help="path to sync.py")
    ap.add_argument("--upload", action="store_true", help="pass --upload to sync.py")
    ap.add_argument("--print-status", action="store_true", help="print one status line and exit")
    ap.add_argument("--since", type=float, default=0, help="with --print-status: epoch; older status = stale")
    a = ap.parse_args(argv)
    out = str(Path(a.out).expanduser())
    if a.print_status:
        print_status(out, a.since)
        return 0
    runner = Runner(out, a.python, a.sync, a.upload)
    httpd = serve(out, a.port, runner)
    if os.environ.get("ARCHIVE_URL"):  # sync.py reads ARCHIVE_URL / ARCHIVE_TOKEN_FILE from the env too
        start_archive_poller(runner, os.environ["ARCHIVE_URL"], os.environ.get("ARCHIVE_TOKEN_FILE"),
                             int(os.environ.get("ARCHIVE_POLL_SECS", "45")))
    sys.stderr.write("sync helper on http://127.0.0.1:%d (out=%s)\n" % (a.port, out))
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
